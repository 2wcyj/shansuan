const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('../frontend/node_modules/typescript');
const file=path.resolve(__dirname,'../frontend/src/recipeName.ts');
assert(fs.existsSync(file),'missing presentation helper for saved recipe names');
const js=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const mod={exports:{}};new Function('exports','module',js)(mod.exports,mod);
const {recipeName}=mod.exports;
const r={name:'牛肉与菜花炖饭',items:[{food_id:'usda-168878',name:'白米饭'},{name:'牛肉（熟瘦肉参考）'},{name:'菜花（煮熟）'},{food_id:'usda-171413',name:'橄榄油'}],nutrition:{energy:751.6}};
const before=JSON.stringify(r);
assert.equal(recipeName(r),'白米饭、牛肉、菜花');
assert.equal(JSON.stringify(r),before,'display must not mutate saved recipe');
assert.equal(recipeName({name:'熟藜麦与三文鱼、大白菜炖饭',items:[{name:'熟藜麦'},{name:'三文鱼（熟）'},{name:'大白菜（煮熟）'}]}),'熟藜麦、三文鱼、大白菜');
assert.equal(recipeName({name:'苹果与酸奶',items:[]}),'苹果与酸奶');
assert.equal(recipeName({name:'原名称炖饭',items:[]}),'原名称炖饭');
const recipes=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../resources/recipes.json'),'utf8'));
assert(recipes.every(r=>!r.name.includes('炖饭')),'catalog must name actual foods instead of generic rice dish');
assert.equal(recipes.find(r=>r.id==='recipe-44').name,'白米饭、牛肉、菜花');
console.log('PASS explicit staple, protein and vegetable names; legacy display; no mutations; catalog names');
